$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$dataDir = Join-Path $scriptDir 'data'

function Update-Q($chFile, $qId, $optA, $optB, $optC, $optD) {
    $path = Join-Path $dataDir $chFile
    $json = [System.IO.File]::ReadAllText($path, [System.Text.Encoding]::UTF8)
    $data = $json | ConvertFrom-Json
    
    $q = $data.questions | Where-Object { $_.id -eq $qId }
    if ($q) {
        if ($optA) { $q.options.A = $optA }
        if ($optB) { $q.options.B = $optB }
        if ($optC) { $q.options.C = $optC }
        if ($optD) { $q.options.D = $optD }
    }
    
    $newJson = $data | ConvertTo-Json -Depth 10
    [System.IO.File]::WriteAllText($path, $newJson, [System.Text.Encoding]::UTF8)
}

