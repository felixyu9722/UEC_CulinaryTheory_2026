    fpath = os.path.join(data_dir, f'chapter{ch_num:02d}.json')
    d = json.load(open(fpath, encoding='utf-8-sig'))
    applied = 0
    for q in d['questions']:
        qid = q['id']
        if qid in updates:
            u = updates[qid]
            if 'question' in u:
                q['question'] = u['question']
            for k in ['A', 'B', 'C', 'D']:
                if k in u['options']:
                    q['options'][k] = u['options'][k]
            applied += 1
    with open(fpath, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
    print(f"Chapter {ch_num:02d}: successfully updated {applied} questions.")

